/* =====================================================================
   PROJECTS — dynamic video gallery
   ---------------------------------------------------------------------
   1. Reads projects.json (generated by scripts/generate-manifest.js)
   2. On GitHub Pages, optionally cross-checks assets/videos via the
      public GitHub API so newly uploaded videos still appear
   3. Renders one card per project, lazy-loads previews, opens a modal
   ===================================================================== */

(function () {
  "use strict";

  const cfg = window.portfolioConfig || {};
  const VIDEO_RE = /\.(mp4|webm|mov)$/i;
  const reduceMotion = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const canHover = window.matchMedia && window.matchMedia("(hover: hover) and (pointer: fine)").matches;

  const videosPath = cfg.videosPath || "assets/videos/";
  const thumbsPath = cfg.thumbnailsPath || "assets/thumbnails/";

  const ICON = {
    arrow: '<svg class="icon" viewBox="0 0 24 24" aria-hidden="true"><path d="M7 17 17 7M8 7h9v9"/></svg>',
    play: '<svg class="icon icon--play" viewBox="0 0 24 24" aria-hidden="true"><path d="M7 4.5v15l12-7.5z"/></svg>'
  };

  /* ---------------- helpers ---------------- */
  const isShowreel = (f) => /^showreel\.(mp4|webm|mov)$/i.test(f);
  const pad = (n) => String(n).padStart(2, "0");
  const fileUrl = (dir, f) => dir + f.split("/").map(encodeURIComponent).join("/");
  const slugOf = (f) => f.replace(/\.[^.]+$/, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const natural = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

  function titleFromFile(file) {
    return file
      .replace(/\.[^.]+$/, "")
      .replace(/([a-z])([A-Z])/g, "$1 $2")
      .replace(/[_\-.]+/g, " ")
      .trim()
      .split(/\s+/)
      .map((w) => (/^\d+$/.test(w) ? w : w.charAt(0).toUpperCase() + w.slice(1)))
      .join(" ");
  }

  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  }

  function withTimeout(promise, ms) {
    return Promise.race([promise, new Promise((_, rej) => setTimeout(() => rej(new Error("timeout")), ms))]);
  }

  /* ---------------- manifest ---------------- */
  async function fetchManifest() {
    try {
      const res = await fetch(cfg.manifestPath || "projects.json", { cache: "no-cache" });
      if (!res.ok) throw new Error("HTTP " + res.status);
      return await res.json();
    } catch (err) {
      if (location.protocol === "file:") {
        console.info("[portfolio] Opened from the file system — projects.json can't be read this way. Run a local server (see README).");
      } else {
        console.warn("[portfolio] Could not load projects.json:", err.message);
      }
      return null;
    }
  }

  function githubRepo() {
    const g = cfg.github || {};
    if (g.owner && g.repo) return g;
    const m = location.hostname.match(/^([a-z0-9-]+)\.github\.io$/i);
    if (!m) return null;
    const first = location.pathname.split("/").filter(Boolean)[0];
    const repo = first && !first.includes(".") ? first : m[1] + ".github.io";
    return { owner: m[1], repo, branch: g.branch || "" };
  }

  /* Lists assets/videos through the public GitHub API (no key needed). */
  async function fetchGithubListing() {
    if (cfg.autoDetectOnGitHub === false) return null;
    const repo = githubRepo();
    if (!repo) return null;

    const key = "portfolio-gh-" + repo.owner + "/" + repo.repo;
    try {
      const cached = JSON.parse(sessionStorage.getItem(key) || "null");
      if (cached && Date.now() - cached.t < 10 * 60 * 1000) return cached.files;
    } catch (e) { /* storage unavailable */ }

    const dir = videosPath.replace(/^\.?\//, "").replace(/\/$/, "");
    const url = "https://api.github.com/repos/" + repo.owner + "/" + repo.repo + "/contents/" + dir + (repo.branch ? "?ref=" + encodeURIComponent(repo.branch) : "");
    try {
      const res = await withTimeout(fetch(url, { headers: { Accept: "application/vnd.github+json" } }), 2500);
      if (!res.ok) return null; // 404 / rate-limited → just trust projects.json
      const data = await res.json();
      if (!Array.isArray(data)) return null;
      const files = data.filter((f) => f.type === "file").map((f) => f.name);
      try { sessionStorage.setItem(key, JSON.stringify({ t: Date.now(), files })); } catch (e) { /* ignore */ }
      return files;
    } catch (e) {
      return null;
    }
  }

  function normalize(manifest, listing) {
    const m = manifest || {};
    let entries = (Array.isArray(m.projects) ? m.projects : [])
      .map((p) => (typeof p === "string" ? { file: p } : p))
      .filter((p) => p && p.file && VIDEO_RE.test(p.file) && !isShowreel(p.file));

    let showreel = m.showreel || (manifest ? "" : "showreel.mp4");

    if (listing) {
      const vids = listing.filter((f) => VIDEO_RE.test(f));
      const order = (f) => [".mp4", ".webm", ".mov"].indexOf(f.slice(f.lastIndexOf(".")).toLowerCase());
      const reel = vids.filter(isShowreel).sort((a, b) => order(a) - order(b))[0];
      showreel = reel || "";
      const known = new Set(entries.map((p) => p.file));
      entries = entries.filter((p) => vids.includes(p.file)); // drop deleted files
      vids.filter((f) => !isShowreel(f) && !known.has(f)).sort(natural).forEach((f) => entries.push({ file: f }));
    }

    const seen = new Set();
    const projects = entries
      .filter((p) => (seen.has(p.file) ? false : seen.add(p.file)))
      .map((p, i) => ({
        index: i,
        file: p.file,
        slug: slugOf(p.file),
        src: fileUrl(videosPath, p.file),
        title: p.title || titleFromFile(p.file),
        category: p.category || cfg.defaultCategory || "Motion Design",
        description: p.description || "",
        software: Array.isArray(p.software) && p.software.length ? p.software : (cfg.defaultSoftware || []),
        thumbnail: p.thumbnail ? (/^(https?:)?\/\//.test(p.thumbnail) || p.thumbnail.includes("/") ? p.thumbnail : fileUrl(thumbsPath, p.thumbnail)) : "",
        year: p.year || ""
      }));

    return {
      showreel: showreel ? fileUrl(videosPath, showreel) : "",
      showreelPoster: m.showreelPoster ? (m.showreelPoster.includes("/") ? m.showreelPoster : fileUrl(thumbsPath, m.showreelPoster)) : "",
      projects
    };
  }

  /* ---------------- rendering ---------------- */
  function layoutClasses(i, n) {
    if (n === 1) return ["card--12"];
    if (n % 2 === 1 && i === n - 1) return ["card--12", "card--last-odd"];
    const pair = Math.floor(i / 2);
    const first = i % 2 === 0;
    const big = pair % 2 === 0 ? first : !first;
    return big ? ["card--7"] : ["card--5", "card--offset"];
  }

  function cardHTML(p, n) {
    const cls = ["card"].concat(layoutClasses(p.index, n)).join(" ");
    return (
      '<article class="' + cls + '" data-index="' + p.index + '" data-reveal-card>' +
        '<div class="card__media" data-open aria-hidden="true">' +
          '<div class="card__inner">' +
            '<span class="card__shimmer">' + esc(pad(p.index + 1)) + "</span>" +
          "</div>" +
          '<span class="card__num">' + pad(p.index + 1) + "</span>" +
          '<span class="card__cursor">View</span>' +
          '<span class="card__badge">' + ICON.play + "</span>" +
        "</div>" +
        '<div class="card__info">' +
          '<div class="card__row">' +
            '<h3 class="card__title">' + esc(p.title) + "</h3>" +
            '<span class="card__cat">' + esc(p.category) + "</span>" +
          "</div>" +
          (p.description ? '<p class="card__desc">' + esc(p.description) + "</p>" : "") +
          '<button class="card__link" type="button" data-open aria-label="View project: ' + esc(p.title) + '">View Project ' + ICON.arrow + "</button>" +
        "</div>" +
      "</article>"
    );
  }

  /* Creates the preview <video>. With no thumbnail it doubles as the cover
     (first frame via #t=0.1 + preload="metadata"). */
  function makeVideo(p, asCover) {
    const v = document.createElement("video");
    v.muted = true;
    v.loop = true;
    v.playsInline = true;
    v.setAttribute("playsinline", "");
    v.setAttribute("muted", "");
    v.setAttribute("aria-hidden", "true");
    v.preload = asCover ? "metadata" : "none";
    v.src = p.src + (asCover ? "#t=0.1" : "");
    return v;
  }

  function hydrateMedia(card, p) {
    if (card.dataset.hydrated) return;
    card.dataset.hydrated = "1";
    const inner = card.querySelector(".card__inner");

    const useVideoCover = () => {
      if (card._video) return;
      const v = makeVideo(p, true);
      card._video = v;
      v.addEventListener("loadeddata", () => v.classList.add("is-visible"), { once: true });
      v.addEventListener("error", () => v.remove(), { once: true });
      inner.appendChild(v);
    };

    if (p.thumbnail) {
      const img = new Image();
      img.alt = "";
      img.decoding = "async";
      img.loading = "lazy";
      img.onerror = () => { img.remove(); useVideoCover(); };
      img.src = p.thumbnail;
      inner.appendChild(img);
    } else {
      useVideoCover();
    }
  }

  function startPreview(card, p) {
    if (reduceMotion) return;
    let v = card._video;
    if (!v) {
      v = makeVideo(p, false);
      card._video = v;
      v.addEventListener("error", () => v.remove(), { once: true });
      card.querySelector(".card__inner").appendChild(v);
    }
    card._hovering = true;
    v.preload = "auto";
    const playing = v.play();
    if (playing && playing.then) {
      playing.then(() => {
        if (!card._hovering) { v.pause(); return; }
        v.classList.add("is-visible");
        card.classList.add("is-previewing");
      }).catch(() => {});
    }
  }

  function stopPreview(card) {
    card._hovering = false;
    const v = card._video;
    card.classList.remove("is-previewing");
    if (v && !v.paused) v.pause();
  }

  /* ---------------- modal ---------------- */
  const modal = {
    el: null, video: null, list: [], current: -1, lastFocus: null,

    init(list) {
      this.list = list;
      this.el = document.getElementById("projectModal");
      this.video = document.getElementById("modalVideo");
      if (!this.el) return;

      this.el.addEventListener("click", (e) => { if (e.target.closest("[data-close]")) this.close(); });
      document.getElementById("modalPrev").addEventListener("click", () => this.step(-1));
      document.getElementById("modalNext").addEventListener("click", () => this.step(1));

      document.addEventListener("keydown", (e) => {
        if (this.el.hidden) return;
        if (e.key === "Escape") this.close();
        else if (e.key === "ArrowRight" && e.target.tagName !== "VIDEO") this.step(1);
        else if (e.key === "ArrowLeft" && e.target.tagName !== "VIDEO") this.step(-1);
        else if (e.key === "Tab") this.trap(e);
      });

      window.addEventListener("hashchange", () => this.fromHash());
      this.fromHash();
    },

    trap(e) {
      const f = this.el.querySelectorAll("button, video[controls], a[href]");
      if (!f.length) return;
      const first = f[0], last = f[f.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    },

    fill(p) {
      const n = this.list.length;
      document.getElementById("modalCounter").textContent = pad(p.index + 1) + " / " + pad(n);
      document.getElementById("modalTitle").textContent = p.title;
      document.getElementById("modalCategory").textContent = p.category;
      document.getElementById("modalCategoryMeta").textContent = p.category;
      document.getElementById("modalDesc").textContent =
        p.description || "A " + (cfg.specialization || "motion graphics").toLowerCase() + " piece by " + (cfg.name || "the designer") + ".";
      document.getElementById("modalSoftware").innerHTML = p.software.map((s) => "<li>" + esc(s) + "</li>").join("");
      document.getElementById("modalYearWrap").hidden = !p.year;
      document.getElementById("modalYear").textContent = p.year;
      document.getElementById("modalPrev").hidden = n < 2;
      document.getElementById("modalNext").hidden = n < 2;

      const v = this.video;
      v.pause();
      v.poster = p.thumbnail || "";
      v.src = p.src;
      v.preload = "auto";
      v.muted = false;
      const play = v.play();
      if (play && play.catch) play.catch(() => { v.muted = true; v.play().catch(() => {}); });
    },

    open(i, fromHash) {
      const p = this.list[i];
      if (!p) return;
      const wasClosed = this.el.hidden;
      this.current = i;
      if (wasClosed) this.lastFocus = document.activeElement;
      this.fill(p);

      if (!fromHash && location.hash !== "#work/" + p.slug) history.replaceState(null, "", "#work/" + p.slug);

      if (wasClosed) {
        this.el.hidden = false;
        document.body.classList.add("is-locked");
        document.dispatchEvent(new CustomEvent("portfolio:modal", { detail: { open: true } }));
        if (window.gsap && !reduceMotion) {
          gsap.fromTo(this.el.querySelector(".modal__backdrop"), { opacity: 0 }, { opacity: 1, duration: 0.5, ease: "power2.out" });
          gsap.fromTo(this.el.querySelector(".modal__panel"), { y: 60, opacity: 0 }, { y: 0, opacity: 1, duration: 0.7, ease: "expo.out" });
        }
        this.el.querySelector(".icon-btn--close").focus({ preventScroll: true });
      } else if (window.gsap && !reduceMotion) {
        gsap.fromTo(this.el.querySelector(".modal__info"), { opacity: 0, y: 16 }, { opacity: 1, y: 0, duration: 0.5, ease: "power3.out" });
      }
    },

    step(dir) {
      const n = this.list.length;
      if (n < 2) return;
      this.open((this.current + dir + n) % n);
    },

    close() {
      if (this.el.hidden) return;
      const done = () => {
        this.el.hidden = true;
        this.video.pause();
        this.video.removeAttribute("src");
        this.video.load();
        document.body.classList.remove("is-locked");
        if (location.hash.indexOf("#work/") === 0) history.replaceState(null, "", "#work");
        if (this.lastFocus && this.lastFocus.focus) this.lastFocus.focus({ preventScroll: true });
        document.dispatchEvent(new CustomEvent("portfolio:modal", { detail: { open: false } }));
      };
      if (window.gsap && !reduceMotion) {
        gsap.to(this.el.querySelector(".modal__panel"), { y: 40, opacity: 0, duration: 0.35, ease: "power2.in" });
        gsap.to(this.el.querySelector(".modal__backdrop"), { opacity: 0, duration: 0.35, onComplete: done });
      } else done();
    },

    fromHash() {
      const m = location.hash.match(/^#work\/(.+)$/);
      if (!m) { if (!this.el.hidden) this.close(); return; }
      const i = this.list.findIndex((p) => p.slug === decodeURIComponent(m[1]));
      if (i > -1) this.open(i, true);
    }
  };

  function render(data) {
    const grid = document.getElementById("projectsGrid");
    const empty = document.getElementById("projectsEmpty");
    const count = document.getElementById("projectCount");
    if (!grid) return;

    const list = data.projects;
    if (count) count.textContent = list.length ? "(" + pad(list.length) + ")" : "";

    if (!list.length) {
      grid.innerHTML = "";
      grid.hidden = true;
      empty.hidden = false;
      return;
    }

    grid.hidden = false;
    empty.hidden = true;
    grid.innerHTML = list.map((p) => cardHTML(p, list.length)).join("");
    const cards = Array.from(grid.querySelectorAll(".card"));

    // Lazy hydrate covers shortly before they scroll into view
    const io = "IntersectionObserver" in window
      ? new IntersectionObserver((entries) => {
          entries.forEach((en) => {
            if (en.isIntersecting) { hydrateMedia(en.target, list[+en.target.dataset.index]); io.unobserve(en.target); }
          });
        }, { rootMargin: "400px 0px" })
      : null;

    cards.forEach((card) => {
      const p = list[+card.dataset.index];
      io ? io.observe(card) : hydrateMedia(card, p);

      card.querySelectorAll("[data-open]").forEach((el) => el.addEventListener("click", () => modal.open(p.index)));

      if (canHover) {
        const media = card.querySelector(".card__media");
        media.addEventListener("mouseenter", () => startPreview(card, p));
        media.addEventListener("mouseleave", () => stopPreview(card));
      }
    });

    // Pause any preview that scrolls off-screen
    if ("IntersectionObserver" in window) {
      const vis = new IntersectionObserver((entries) => entries.forEach((en) => { if (!en.isIntersecting) stopPreview(en.target); }));
      cards.forEach((c) => vis.observe(c));
    }

    modal.init(list);
    window.__projectsRendered = { cards, projects: list };
    document.dispatchEvent(new CustomEvent("projects:rendered", { detail: { cards, projects: list } }));
  }

  /* ---------------- boot ---------------- */
  const ready = (async () => {
    const [manifest, listing] = await Promise.all([fetchManifest(), fetchGithubListing()]);
    const data = normalize(manifest, listing);
    return data;
  })();

  // main.js uses this for the showreel
  window.portfolioManifest = ready;

  const onDom = (fn) => (document.readyState === "loading" ? document.addEventListener("DOMContentLoaded", fn) : fn());
  onDom(() => ready.then(render).catch((err) => {
    console.error("[portfolio] Gallery failed:", err);
    render({ projects: [] });
  }));

  // exposed for testing / other scripts
  window.PortfolioProjects = { titleFromFile, layoutClasses };
})();
